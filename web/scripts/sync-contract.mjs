// Copies the ConfidentialPayLinks ABI (and, for local demos, the test token bytecode) from the Foundry build into
// src/abi.generated.ts. Run after `forge build` in ../contracts:  npm run sync-contract
import { readFileSync, writeFileSync } from 'node:fs';
import { fileURLToPath } from 'node:url';

const read = (p) => JSON.parse(readFileSync(fileURLToPath(new URL(`../../contracts/out/${p}`, import.meta.url)), 'utf8'));
const links = read('ConfidentialPayLinks.sol/ConfidentialPayLinks.json');
const out = `// Generated by scripts/sync-contract.mjs from contracts/out. Do not edit by hand.
export const payLinksAbi = ${JSON.stringify(links.abi, null, 2)} as const;
`;
writeFileSync(fileURLToPath(new URL('../src/abi.generated.ts', import.meta.url)), out);
console.log('wrote src/abi.generated.ts');
